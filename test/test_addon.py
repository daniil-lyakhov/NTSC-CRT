"""Tests for the NTSC-CRT Blender addon (real-time frame handler version).

Exercises addon registration, UI properties, helper functions, the toggle
operator, and the frame_change_post handler that processes frames in real-time.

Run inside Blender in background mode:
    NTSC_CRT_PATH=/path/to/NTSC-CRT/python \
    /path/to/blender --background --python test/test_addon.py

Requires test/test_input.mp4 (generated by test runner or manually).
"""

import os
import sys
import unittest

# ---------------------------------------------------------------------------
# Path setup
# ---------------------------------------------------------------------------
_TEST_DIR = os.path.dirname(os.path.abspath(__file__))
_REPO_ROOT = os.path.abspath(os.path.join(_TEST_DIR, os.pardir))

_NTSC_CRT_PATH = os.environ.get("NTSC_CRT_PATH")
if not _NTSC_CRT_PATH:
    _NTSC_CRT_PATH = os.path.join(_REPO_ROOT, "python")

for _p in (_NTSC_CRT_PATH, os.path.join(_NTSC_CRT_PATH, "lib")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

_ADDON_DIR = os.path.join(_REPO_ROOT, "examples", "blender_addon")

import bpy
import importlib.util

# Force-load the addon module from the repo, not Blender's installed copy
_spec = importlib.util.spec_from_file_location(
    "ntsc_crt_addon", os.path.join(_ADDON_DIR, "main.py")
)
addon_module = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(addon_module)

TEST_VIDEO = os.path.join(_TEST_DIR, "test_input.mp4")

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _ensure_registered():
    if not hasattr(bpy.types.Scene, "ntsc_crt"):
        addon_module.register()


def _clear_sequencer():
    """Remove all strips from the sequencer."""
    scene = bpy.context.scene
    if scene.sequence_editor is None:
        return
    _, strips = addon_module._get_strips(scene)
    for s in list(strips):
        strips.remove(s)


def _add_movie_strip(filepath, channel=1, frame_start=1):
    """Add a movie strip and make it active. Returns the strip."""
    scene = bpy.context.scene
    if scene.sequence_editor is None:
        scene.sequence_editor_create()
    _, strips = addon_module._get_strips(scene)
    strip = strips.new_movie(
        name="Test Video",
        filepath=filepath,
        channel=channel,
        frame_start=frame_start,
    )
    scene.sequence_editor.active_strip = strip
    return strip


def _reset_props():
    """Reset all addon properties to their defaults."""
    props = bpy.context.scene.ntsc_crt
    props.enabled = False
    props.system = "ntsc"
    props.hue = 0
    props.brightness = 0
    props.contrast = 180
    props.saturation = 10
    props.black_point = 0
    props.white_point = 100
    props.scanlines = True
    props.blend = True
    props.v_fac = 0
    props.noise = 24
    props.artifact_hue = 0
    props.num_frames = 4
    props.progressive = False
    props.raw = False
    props.as_color = True
    props.xoffset = 0
    props.yoffset = 0
    props.do_aberration = False


def _disable_handler():
    """Ensure handler is removed and state is clean."""
    handler = addon_module._ntsc_frame_handler
    if handler in bpy.app.handlers.frame_change_post:
        bpy.app.handlers.frame_change_post.remove(handler)
    addon_module._HandlerState.release_all()


# ===================================================================
# Test: Registration
# ===================================================================

class TestAddonRegistration(unittest.TestCase):

    def test_register(self):
        addon_module.register()
        self.assertTrue(hasattr(bpy.types.Scene, "ntsc_crt"))

    def test_unregister_and_reregister(self):
        _ensure_registered()
        addon_module.unregister()
        self.assertFalse(hasattr(bpy.types.Scene, "ntsc_crt"))
        addon_module.register()
        self.assertTrue(hasattr(bpy.types.Scene, "ntsc_crt"))

    def test_unregister_removes_handler(self):
        _ensure_registered()
        # Manually add handler
        handler = addon_module._ntsc_frame_handler
        if handler not in bpy.app.handlers.frame_change_post:
            bpy.app.handlers.frame_change_post.append(handler)
        addon_module.unregister()
        self.assertNotIn(handler, bpy.app.handlers.frame_change_post)
        addon_module.register()


