@unittest.skipUnless(os.path.isfile(TEST_VIDEO), "test_input.mp4 missing")
class TestFrameHandlerNTSC(unittest.TestCase):
    """Test the frame_change_post handler processes frames correctly."""

    @classmethod
    def setUpClass(cls):
        _ensure_registered()

    def setUp(self):
        _clear_sequencer()
        _reset_props()
        _disable_handler()
        bpy.context.scene.frame_set(1)
        self.props = bpy.context.scene.ntsc_crt
        self.props.num_frames = 1  # fast
        self.strip = _add_movie_strip(TEST_VIDEO)

    def tearDown(self):
        _disable_handler()
        _clear_sequencer()
        # Remove preview image if it exists
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        if img is not None:
            bpy.data.images.remove(img)

    def _enable_and_process(self):
        """Enable handler and process current frame."""
        self.props.enabled = True
        addon_module._ntsc_frame_handler(bpy.context.scene)

    def test_handler_does_nothing_when_disabled(self):
        self.props.enabled = False
        addon_module._ntsc_frame_handler(bpy.context.scene)
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        self.assertIsNone(img)

    def test_handler_creates_preview_image(self):
        self._enable_and_process()
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        self.assertIsNotNone(img)
        self.assertGreater(img.size[0], 0)
        self.assertGreater(img.size[1], 0)

    def test_handler_preview_image_size_matches_video(self):
        import cv2
        cap = cv2.VideoCapture(TEST_VIDEO)
        expected_w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
        expected_h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
        cap.release()

        self._enable_and_process()
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        self.assertEqual(img.size[0], expected_w)
        self.assertEqual(img.size[1], expected_h)

    def test_handler_preview_has_nonzero_pixels(self):
        import numpy as np
        self._enable_and_process()
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        pixels = np.zeros(len(img.pixels), dtype=np.float32)
        img.pixels.foreach_get(pixels)
        self.assertGreater(np.max(pixels), 0.0)

    def test_handler_processes_different_frames(self):
        import numpy as np
        self.props.enabled = True

        # Process frame 1
        bpy.context.scene.frame_set(1)
        addon_module._ntsc_frame_handler(bpy.context.scene)
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        pixels_1 = np.zeros(len(img.pixels), dtype=np.float32)
        img.pixels.foreach_get(pixels_1)

        # Process frame 30
        bpy.context.scene.frame_set(30)
        addon_module._ntsc_frame_handler(bpy.context.scene)
        pixels_30 = np.zeros(len(img.pixels), dtype=np.float32)
        img.pixels.foreach_get(pixels_30)

        # They should be different (CRT noise if nothing else)
        self.assertFalse(np.array_equal(pixels_1, pixels_30))

    def test_handler_respects_custom_settings(self):
        import numpy as np
        self.props.enabled = True

        # Default settings
        bpy.context.scene.frame_set(1)
        addon_module._ntsc_frame_handler(bpy.context.scene)
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        pixels_default = np.zeros(len(img.pixels), dtype=np.float32)
        img.pixels.foreach_get(pixels_default)

        # Change contrast significantly
        self.props.contrast = 500
        # Invalidate CRT cache to pick up new settings
        addon_module._HandlerState.release_all()
        addon_module._ntsc_frame_handler(bpy.context.scene)
        pixels_high = np.zeros(len(img.pixels), dtype=np.float32)
        img.pixels.foreach_get(pixels_high)

        self.assertFalse(np.array_equal(pixels_default, pixels_high))

    def test_handler_skips_out_of_range_frame(self):
        self.props.enabled = True
        # Move to a frame outside the strip range
        bpy.context.scene.frame_set(9999)
        addon_module._ntsc_frame_handler(bpy.context.scene)
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        self.assertIsNone(img)

    def test_handler_no_strip(self):
        _clear_sequencer()
        self.props.enabled = True
        addon_module._ntsc_frame_handler(bpy.context.scene)
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        self.assertIsNone(img)

    def test_monochrome(self):
        self.props.as_color = False
        self._enable_and_process()
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        self.assertIsNotNone(img)

    def test_progressive(self):
        self.props.progressive = True
        self._enable_and_process()
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        self.assertIsNotNone(img)

    def test_no_scanlines_no_blend(self):
        self.props.scanlines = False
        self.props.blend = False
        self._enable_and_process()
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        self.assertIsNotNone(img)

    def test_high_noise(self):
        self.props.noise = 200
        self._enable_and_process()
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        self.assertIsNotNone(img)

    def test_offsets(self):
        self.props.xoffset = 20
        self.props.yoffset = -10
        self._enable_and_process()
        img = bpy.data.images.get(addon_module._HandlerState.preview_name)
        self.assertIsNotNone(img)


